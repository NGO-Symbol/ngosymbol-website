const imageExtensions = new Set(['.jpg', '.jpeg', '.png', '.tif', '.tiff', '.webp'])
function walk(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap(entry => entry.isDirectory() ? walk(join(directory, entry.name)) : [join(directory, entry.name)])
    .filter(file => imageExtensions.has(extname(file).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, 'uk', { numeric: true }))
}

function creditFor(file) {
  const name = basename(file)
  if (/Chekal/i.test(name)) return 'Петро Чекаль'
  if (/^1Y4A/i.test(name)) return 'Олександр Осіпов'
  return undefined
}

rmSync(outputRoot, { recursive: true, force: true })
mkdirSync(outputRoot, { recursive: true })

const groups = {}
let imported = 0
let duplicates = 0

for (const [folder, slug, title] of folders) {
  const sourceDirectory = join(sourceRoot, folder)
  const destinationDirectory = join(outputRoot, slug, title === 'Excel-art' ? 'excel-art' : title === 'Заяви' ? 'zaiavy' : title === 'Мімік' ? 'mimik' : title === 'Сучасна мода' ? 'suchasna-moda' : 'work')
  mkdirSync(destinationDirectory, { recursive: true })

  const seen = new Set()
  const photos = []
  for (const source of walk(sourceDirectory)) {
    // The archive's accidental copies are byte-for-byte duplicates (usually marked “(1)”).
    const signature = createHash('sha256').update(readFileSync(source)).digest('hex')
    if (seen.has(signature)) {
      duplicates++
      continue
    }
    seen.add(signature)

    const number = String(photos.length + 1).padStart(3, '0')
    const destination = join(destinationDirectory, `${number}.jpg`)
    execFileSync('convert', [source, '-auto-orient', '-resize', '1800x1800>', '-strip', '-sampling-factor', '4:2:0', '-quality', '84', destination])
    const publicPath = `/${relative(join(repositoryRoot, 'apps/main/public'), destination).split('\\').join('/')}`
    photos.push({ src: publicPath, ...(creditFor(source) ? { credit: creditFor(source) } : {}) })
    imported++
  }

  groups[slug] ??= []
  groups[slug].push({ title, photos })
}

const manifest = `// Generated by scripts/import-psd-artist-photos.mjs from the curator-sorted local archive.\n` +
  `// Do not hand-edit paths; update the source folders and run the importer again.\n` +
  `export interface ArtistWorkPhoto { src: string, credit?: string }\n` +
  `export interface ArtistWorkPhotoGroup { title: string, photos: ArtistWorkPhoto[] }\n\n` +
  `export const artistPhotoGroups: Record<string, ArtistWorkPhotoGroup[]> = ${JSON.stringify(groups, null, 2)}\n`

mkdirSync(dirname(manifestPath), { recursive: true })
writeFileSync(manifestPath, manifest)
console.log(`Imported ${imported} photographs; skipped ${duplicates} exact duplicates.`)
